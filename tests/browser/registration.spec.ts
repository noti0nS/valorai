test('server enforces confirmation, session isolation, single-use codes, and origin', async ({ playwright }) => {
  const owner = await playwright.request.newContext({ baseURL: origin });
  const stranger = await playwright.request.newContext({ baseURL: origin });
  const data = fixture();
  const response = await post(owner, 'register', data);
  expect(response.status()).toBe(201);
  expect(response.headers()['set-cookie']).toContain('HttpOnly');
  const finance = { income: 2000, fixedExpenses: 1000, goal: 'reserve' };
  expect((await post(owner, 'finance', finance)).status()).toBe(403);
  expect((await stranger.get('/api/demo-inbox')).status()).toBe(401);
  expect((await owner.post('/api/confirm', { data: { code: '000000' }, headers: { Origin: 'https://invalid.example' } })).status()).toBe(403);
  const inbox = await (await owner.get('/api/demo-inbox')).json();
  const confirmation = await post(owner, 'confirm', { code: inbox.code });
  expect(confirmation.status()).toBe(200);
  const confirmed = await confirmation.json();
  expect(confirmed.account.emailVerified).toBe(false);
  expect(confirmed.account.demoConfirmed).toBe(true);
  expect((await post(owner, 'confirm', { code: inbox.code })).status()).toBe(409);
  expect((await post(stranger, 'finance', finance)).status()).toBe(401);
  expect((await post(owner, 'finance', finance)).status()).toBe(200);
  const duplicate = await post(stranger, 'register', data);
  expect(duplicate.status()).toBe(409);
  await post(owner, 'deactivate', { password: data.password });
  expect((await owner.get('/api/session')).status()).toBe(401);
  expect((await post(stranger, 'login', { identifier: data.email, password: data.password })).status()).toBe(401);
  await owner.dispose(); await stranger.dispose();
});
