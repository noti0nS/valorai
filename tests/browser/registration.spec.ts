import { test, expect, type APIRequestContext } from '@playwright/test';
import crypto from 'node:crypto';
const origin = 'http://127.0.0.1:8787';
function fixture() {
  const n = Array.from(crypto.randomBytes(9), b => b % 10);
  for (const size of [9, 10]) n.push((n.slice(0, size).reduce((sum, v, i) => sum + v * (size + 1 - i), 0) * 10 % 11) % 10);
  return { name: 'Cliente de Teste', cpf: n.join(''), birthDate: '1995-06-15', phone: '82999990000', postalCode: '57020000', state: 'AL', city: 'Maceió', email: `test-${crypto.randomUUID()}@example.com`, password: 'PrototypeOnly8', confirmPassword: 'PrototypeOnly8', demoConsent: true };
}
const post = (client: APIRequestContext, route: string, data: unknown) => client.post(`/api/${route}`, { data, headers: { Origin: origin } });

